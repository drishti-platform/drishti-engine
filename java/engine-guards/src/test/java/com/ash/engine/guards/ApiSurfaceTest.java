package com.ash.engine.guards;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;

import com.ash.tools.guards.kit.ApiSurface;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import org.junit.jupiter.api.Test;

/**
 * The public surface of every published module, additive only within a major (specification section 13): {@code java/<module>/api-surface.txt}
 * lists every public and protected member of every public class of the module's packages, one sorted line each, built from the
 * compiled classes. A removed or changed line fails (a major version); an added line fails until the file is rewritten in the same
 * commit, so review sees it: {@code ./mvnw verify -Dengine.api.surface.write=true} (a removal is written only with
 * {@code -Dengine.api.surface.major=true}).
 */
class ApiSurfaceTest {

    @Test
    void everyModulesPublicSurfaceIsItsCommittedBaselineAndOnlyGrows() throws Exception {
        List<String> problems = new ArrayList<>();
        for (List<String> m : Repo.MODULES) {
            Path module = Repo.JAVA.resolve(m.get(0));
            List<String> now = new ArrayList<>();
            for (String pkg : m.subList(1, m.size())) {
                now.addAll(ApiSurface.of(module.resolve("target/classes"), pkg, ApiSurfaceTest.class.getClassLoader()));
            }
            now = now.stream().sorted().toList();
            assertFalse(now.isEmpty(), module + ": no public API found");
            Path file = module.resolve("api-surface.txt");
            List<String> was = Files.exists(file) ? Files.readAllLines(file, StandardCharsets.UTF_8).stream()
                    .filter(l -> !l.startsWith("#") && !l.isBlank()).toList() : List.of();
            List<String> removed = new ArrayList<>(was);
            removed.removeAll(now);
            List<String> added = new ArrayList<>(now);
            added.removeAll(was);
            if (Boolean.getBoolean("engine.api.surface.write") && (removed.isEmpty() || Boolean.getBoolean("engine.api.surface.major"))) {
                List<String> out = new ArrayList<>();
                out.add("# Copyright (c) 2026 Ashutosh Sinha <ajsinha@gmail.com>. All rights reserved. Drishti Engine. Proprietary: see LICENSE.");
                out.add("# Generated by ApiSurfaceTest (engine-guards): the public and protected API of " + m.get(0)
                        + ". Additive only within a major: a removed line needs a major version. Review the diff; do not edit.");
                out.addAll(now);
                Files.write(file, out, StandardCharsets.UTF_8);
                continue;
            }
            removed.forEach(r -> problems.add(m.get(0) + " removed or changed (needs a major version): " + r));
            added.forEach(a -> problems.add(m.get(0) + " added (rewrite " + m.get(0) + "/api-surface.txt in the same commit): " + a));
        }
        assertEquals(List.of(), problems, "the public surface differs from the committed baselines");
    }
}
